// MOR-4300: a band-plan region change changes what the capabilities
// payload publishes (region-gated band-selector rows — display only,
// 4 m), so a successful `selectBandPlanRegion` re-reads capabilities
// once and stores them; a failed region POST must not re-read, a failed
// re-read is swallowed like the store's other errors (the region switch
// itself still stands), and a re-read that resolves after a newer
// region change is discarded.
//
// The capabilities documents are the producer-backed golden payloads in
// frontend/src/lib/transport/__tests__/fixtures/state-wire-goldens.json
// (IC-7300 / IC-7300MK2 `capabilities` entries), generated by
// scripts/gen_state_wire_goldens.py and kept current by the Python suite
// tests/web/test_state_wire_goldens.py; tests/test_band_regions_4m.py
// serves the same payloads over the real HTTP seam end to end. Only
// `fetch` is mocked — the documents go through the real
// fetchCapabilities → validateCapabilities parse path.
import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import { validateCapabilities } from '$lib/types/capabilities';
import goldens from '../../transport/__tests__/fixtures/state-wire-goldens.json';

type GoldenEntry = { capabilities: unknown };
const goldenDocs = goldens as unknown as Record<string, GoldenEntry>;

/** The validated form of a golden document (what the store must hold). */
function validated(model: string): ReturnType<typeof validateCapabilities> {
  return validateCapabilities(structuredClone(goldenDocs[model].capabilities));
}

function capsResponse(doc: unknown): Response {
  return { ok: true, json: async () => structuredClone(doc) } as Response;
}

const configOk = { ok: true, json: async () => ({}) } as Response;

describe('band-plan region store: capabilities re-read on region change (MOR-4300)', () => {
  let store: typeof import('../band-plan-region.svelte');
  let caps: typeof import('../capabilities.svelte');

  beforeEach(async () => {
    vi.resetModules();
    vi.stubGlobal('fetch', vi.fn());
    store = await import('../band-plan-region.svelte');
    caps = await import('../capabilities.svelte');
  });

  afterEach(() => {
    vi.unstubAllGlobals();
    vi.resetModules();
  });

  /** Route `/config` POSTs to `configOk`; leave `/capabilities` to `caps`. */
  function mockConfigPost(ok: boolean): void {
    (globalThis.fetch as unknown as ReturnType<typeof vi.fn>).mockImplementation(
      async () => (ok ? configOk : ({ ok: false } as Response)),
    );
  }

  function mockConfigOkAndCaps(caps: Response): void {
    (globalThis.fetch as unknown as ReturnType<typeof vi.fn>).mockImplementation(
      async (input: RequestInfo | URL, init?: RequestInit) => {
        const url = String(input);
        if (url.endsWith('/capabilities')) return caps;
        if (url.endsWith('/config') && init?.method === 'POST') return configOk;
        throw new Error(`unexpected fetch ${url}`);
      },
    );
  }

  it('re-reads capabilities once after a successful region switch and stores the validated golden document', async () => {
    mockConfigOkAndCaps(capsResponse(goldenDocs['IC-7300'].capabilities));

    await expect(store.selectBandPlanRegion('IARU-R1')).resolves.toBe(true);

    await vi.waitFor(() => expect(caps.getCapabilities()).toEqual(validated('IC-7300')));
    const fetchMock = globalThis.fetch as unknown as ReturnType<typeof vi.fn>;
    expect(
      fetchMock.mock.calls.filter(([input]) => String(input).endsWith('/capabilities')),
    ).toHaveLength(1);
    expect(store.getBandPlanRegion()).toBe('IARU-R1');
  });

  it('does not re-read when the region switch fails', async () => {
    mockConfigPost(false);

    await expect(store.selectBandPlanRegion('IARU-R1')).resolves.toBe(false);

    expect(globalThis.fetch).toHaveBeenCalledTimes(1);
    expect(caps.getCapabilities()).toBeNull();
  });

  it('swallows a failed capabilities re-read: the region switch still stands', async () => {
    mockConfigOkAndCaps(({ ok: false } as Response));

    await expect(store.selectBandPlanRegion('IARU-R1')).resolves.toBe(true);

    await vi.waitFor(() =>
      expect(
        (globalThis.fetch as unknown as ReturnType<typeof vi.fn>).mock.calls.some(
          ([input]) => String(input).endsWith('/capabilities'),
        ),
      ).toBe(true),
    );
    await new Promise((resolve) => setTimeout(resolve, 0));
    expect(store.getBandPlanRegion()).toBe('IARU-R1');
    expect(caps.getCapabilities()).toBeNull();
  });

  it('discards a re-read that resolves after a newer region change (R1 lands last, US stays)', async () => {
    // Two quick switches (IARU-R1, then US): each fires one capabilities
    // re-read. The US re-read resolves first and must be stored; the
    // older R1 re-read resolves afterwards and must be discarded, or it
    // would overwrite the US document with the R1 one.
    const pending: Array<(response: Response) => void> = [];
    (globalThis.fetch as unknown as ReturnType<typeof vi.fn>).mockImplementation(
      async (input: RequestInfo | URL, init?: RequestInit) => {
        const url = String(input);
        if (url.endsWith('/capabilities')) {
          return new Promise<Response>((resolve) => pending.push(resolve));
        }
        if (url.endsWith('/config') && init?.method === 'POST') return configOk;
        throw new Error(`unexpected fetch ${url}`);
      },
    );

    await expect(store.selectBandPlanRegion('IARU-R1')).resolves.toBe(true);
    await expect(store.selectBandPlanRegion('US')).resolves.toBe(true);
    expect(pending).toHaveLength(2); // R1's read, then US's read

    pending[1](capsResponse(goldenDocs['IC-7300MK2'].capabilities)); // US reply
    await vi.waitFor(() =>
      expect(caps.getCapabilities()).toEqual(validated('IC-7300MK2')),
    );

    pending[0](capsResponse(goldenDocs['IC-7300'].capabilities)); // stale R1 reply
    await new Promise((resolve) => setTimeout(resolve, 0));
    await new Promise((resolve) => setTimeout(resolve, 0));
    expect(caps.getCapabilities()).toEqual(validated('IC-7300MK2'));
    expect(store.getBandPlanRegion()).toBe('US');
  });
});
